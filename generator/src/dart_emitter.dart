/// Writes the Dart TDLib API (`lib/src/tdapi`) for a parsed schema.
///
/// * every abstract type becomes a `sealed class` with a `fromJson` factory
///   and an `Undecoded<Type>` subtype for types newer than this API;
/// * every constructor becomes a `final class`;
/// * every function becomes `final class X extends TdFunction<Result>`;
/// * JSON decoding is one `tdObjectFactories` map lookup;
/// * int64 values are read from strings and written back as strings.
library;

import 'dart:io';

import 'tl_parser.dart';

/// Generates the API for [schema] into [outDir].
void emitDartApi(TlSchema schema, Directory outDir) {
  final api = _Api(schema);
  for (final sub in ['objects', 'functions']) {
    final dir = Directory('${outDir.path}/$sub');
    if (dir.existsSync()) dir.deleteSync(recursive: true);
    dir.createSync(recursive: true);
  }
  for (final stale in ['object.dart', 'function.dart']) {
    final file = File('${outDir.path}/$stale');
    if (file.existsSync()) file.deleteSync();
  }

  final parts = <String>[];
  void write(String path, String body) {
    parts.add(path);
    File('${outDir.path}/$path')
        .writeAsStringSync("$_header\npart of '../tdapi.dart';\n\n$body");
  }

  final classes = [...schema.classes]..sort((a, b) => a.name.compareTo(b.name));
  for (final c in classes) {
    write('objects/${snakeCase(dartClass(c.name))}.dart', api.family(c));
  }
  for (final t in schema.types) {
    if (schema.classNamed(t.result) != null) continue;
    write('objects/${snakeCase(dartClass(t.name))}.dart',
        api.object(t, 'TdObject'));
  }
  for (final f in schema.functions) {
    write('functions/${snakeCase(dartClass(f.name))}.dart', api.function(f));
  }
  parts.sort();

  File('${outDir.path}/tdapi.dart').writeAsStringSync(_library(
    parts: parts,
    factories: [
      for (final t in schema.types)
        "  '${t.name}': ${dartClass(t.name)}.fromJson,",
    ],
  ));
}

const _header = '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
    "// Generated by generator/generate.dart from TDLib's td_api.tl.\n";

/// Members every generated class already has; fields with these names get
/// a `Value` suffix.
const _reservedMembers = {
  'extra',
  'clientId',
  'toJson',
  'copyWith',
  'getConstructor',
  'hashCode',
  'runtimeType',
  'toString',
  'noSuchMethod',
  'canBeCalledSynchronously',
};

const _primitives = {
  'int32': 'int',
  'int53': 'int',
  'int64': 'int',
  'double': 'double',
  'string': 'String',
  'bytes': 'String',
  'Bool': 'bool',
};

const _readers = {
  'int32': '_readInt',
  'int53': '_readInt',
  'int64': '_readInt',
  'double': '_readDouble',
  'string': '_readString',
  'bytes': '_readString',
  'Bool': '_readBool',
};

/// Dart class name of a TL type or constructor.
String dartClass(String tlName) {
  final name = upperFirst(tlName);
  return name == 'Error' ? 'TdError' : name;
}

String upperFirst(String s) =>
    s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);

String camelCase(String snake) {
  final parts = snake.split('_');
  return parts.first + parts.skip(1).map(upperFirst).join();
}

String snakeCase(String name) => name
    .replaceAllMapped(RegExp(r'(.)([A-Z][a-z]+)'), (m) => '${m[1]}_${m[2]}')
    .replaceAllMapped(RegExp(r'([a-z0-9])([A-Z])'), (m) => '${m[1]}_${m[2]}')
    .toLowerCase();

String _dartType(TlType type) {
  if (type.isVector) return 'List<${_dartType(type.element!)}>';
  return _primitives[type.name] ?? dartClass(type.name);
}

String _doc(String text, [String indent = '']) {
  final clean = text.trim();
  return clean.isEmpty ? '' : '$indent/// $clean\n';
}

String _article(String word) => 'AEIOU'.contains(word[0]) ? 'An' : 'A';

class _Field {
  _Field(TlParam param)
      : tlName = param.name,
        type = param.type,
        doc = param.description,
        name = _fieldName(param.name),
        nullable = param.type.isObject &&
            (param.description.contains('may be null') ||
                param.description.contains('pass null'));

  static String _fieldName(String tlName) {
    final name = camelCase(tlName);
    return _reservedMembers.contains(name) ? '${name}Value' : name;
  }

  final String tlName;
  final TlType type;
  final String doc;
  final String name;
  final bool nullable;

  String get dartType => _dartType(type) + (nullable ? '?' : '');

  String read(String value) => _read(type, value, nullable, 0);

  static String _read(TlType type, String value, bool nullable, int depth) {
    if (type.isVector) {
      final element = type.element!;
      final v = depth == 0 ? 'e' : 'e$depth';
      final reader = _readers[element.name] ??
          '($v) => ${_read(element, v, false, depth + 1)}';
      return '_readList<${_dartType(element)}>($value, '
          '${element.isVector ? '($v) => ${_read(element, v, false, depth + 1)}' : reader})';
    }
    final reader = _readers[type.name];
    if (reader != null) return '$reader($value)';
    final cls = dartClass(type.name);
    return nullable
        ? '_readOptional($value, $cls.fromJson)'
        : '_readObject($value, $cls.fromJson)';
  }

  String write(String value) => _write(type, value, nullable, 0);

  static String _write(TlType type, String value, bool nullable, int depth) {
    if (type.isVector) {
      final element = type.element!;
      if (element.isBuiltIn && element.name != 'int64') return value;
      final v = depth == 0 ? 'e' : 'e$depth';
      return '[for (final $v in $value) ${_write(element, v, false, depth + 1)}]';
    }
    if (type.name == 'int64') return '$value.toString()';
    if (type.isBuiltIn) return value;
    return nullable ? '$value?.toJson()' : '$value.toJson()';
  }
}

class _Api {
  _Api(this.schema) {
    // Objects TDLib sends at the top level carry "@extra" and "@client_id":
    // function results and updates.
    receivable.addAll(['TdError', 'Ok']);
    for (final f in schema.functions) {
      if (schema.classNamed(f.result) != null) {
        receivable
            .addAll(schema.variantsOf(f.result).map((t) => dartClass(t.name)));
      } else {
        receivable.add(dartClass(f.result));
      }
    }
    receivable
        .addAll(schema.variantsOf('Update').map((t) => dartClass(t.name)));
  }

  final TlSchema schema;
  final Set<String> receivable = {};

  String family(TlClass c) {
    final name = dartClass(c.name);
    final undecoded = 'Undecoded$name';
    final variants = schema.variantsOf(c.name).toList();
    final out = StringBuffer()
      ..write(_doc(c.description))
      ..writeln('///')
      ..writeln(
          '/// One of: ${variants.map((v) => '[${dartClass(v.name)}]').join(', ')}; '
          'or [$undecoded] for a type newer than this API.')
      ..writeln('sealed class $name extends TdObject {')
      ..writeln('  const $name();')
      ..writeln()
      ..writeln('  /// Parses whichever [$name] subtype the JSON describes.')
      ..writeln('  factory $name.fromJson(Map<String, dynamic> json) {')
      ..writeln(
          "    final object = tdObjectFactories[json['@type']]?.call(json);")
      ..writeln('    return object is $name ? object : $undecoded(json);')
      ..writeln('  }')
      ..writeln()
      ..writeln('  /// Returns a copy of this object.')
      ..writeln('  $name copyWith();')
      ..writeln('}')
      ..writeln()
      ..writeln('/// ${_article(name)} [$name] this API can\'t decode '
          '(sent by a newer TDLib).')
      ..writeln('final class $undecoded extends $name {')
      ..writeln('  const $undecoded(this.json);')
      ..writeln()
      ..writeln('  /// The raw TDLib JSON object.')
      ..writeln('  final Map<String, dynamic> json;')
      ..writeln()
      ..writeln('  @override')
      ..writeln("  dynamic get extra => json['@extra'];")
      ..writeln()
      ..writeln('  @override')
      ..writeln("  int? get clientId => _readClientId(json['@client_id']);")
      ..writeln()
      ..writeln('  @override')
      ..writeln('  Map<String, dynamic> toJson() => json;')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  $undecoded copyWith() => this;')
      ..writeln()
      ..writeln('  @override')
      ..writeln("  String getConstructor() => _readString(json['@type']);")
      ..writeln('}');
    for (final v in variants) {
      out
        ..writeln()
        ..write(object(v, name));
    }
    return out.toString();
  }

  String object(TlConstructor t, String parent) {
    final name = dartClass(t.name);
    return '${_doc(t.description)}final class $name extends $parent {\n'
        '${_body(t, name, receivable: receivable.contains(name), overrideCopyWith: parent != 'TdObject')}'
        '}\n';
  }

  String function(TlConstructor f) {
    final name = dartClass(f.name);
    final result = dartClass(f.result);
    return '${_doc(f.description)}///\n/// Returns [$result].\n'
        'final class $name extends TdFunction<$result> {\n'
        '${_body(f, name, receivable: false, overrideCopyWith: false)}'
        '}\n';
  }

  String _body(
    TlConstructor c,
    String name, {
    required bool receivable,
    required bool overrideCopyWith,
  }) {
    final fields = [for (final p in c.params) _Field(p)];
    final out = StringBuffer();

    // Constructor.
    final params = [
      for (final f in fields) '${f.nullable ? '' : 'required '}this.${f.name}',
      if (receivable) ...['this.extra', 'this.clientId'],
    ];
    out.write(_doc(c.description, '  '));
    out.writeln(params.isEmpty
        ? '  const $name();'
        : '  const $name({\n${params.map((p) => '    $p,\n').join()}  });');

    // Fields.
    for (final f in fields) {
      out
        ..writeln()
        ..write(_doc(f.doc, '  '))
        ..writeln('  final ${f.dartType} ${f.name};');
    }
    if (receivable) {
      out
        ..writeln()
        ..writeln('  /// "@extra" of the request this object answers.')
        ..writeln('  @override')
        ..writeln('  final dynamic extra;')
        ..writeln()
        ..writeln('  /// Identifier of the TDLib client that sent this object.')
        ..writeln('  @override')
        ..writeln('  final int? clientId;');
    }

    // fromJson, for objects.
    if (!c.isFunction) {
      final args = [
        for (final f in fields) "${f.name}: ${f.read("json['${f.tlName}']")}",
        if (receivable) ...[
          "extra: json['@extra']",
          "clientId: _readClientId(json['@client_id'])",
        ],
      ];
      out
        ..writeln()
        ..writeln('  /// Parses a [$name] from TDLib JSON.')
        ..writeln(args.isEmpty
            ? '  factory $name.fromJson(Map<String, dynamic> json) =>\n'
                '      const $name();'
            : '  factory $name.fromJson(Map<String, dynamic> json) => $name(\n'
                '${args.map((a) => '        $a,\n').join()}      );');
    }

    // toJson.
    final entries = [
      "'@type': CONSTRUCTOR",
      for (final f in fields) "'${f.tlName}': ${f.write(f.name)}",
      if (c.isFunction) "if (extra != null) '@extra': extra",
    ];
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln(c.isFunction
          ? '  Map<String, dynamic> toJson([dynamic extra]) => {'
          : '  Map<String, dynamic> toJson() => {')
      ..write(entries.map((e) => '        $e,\n').join())
      ..writeln('      };');

    // copyWith.
    final copyParams = [
      for (final f in fields) '${_dartType(f.type)}? ${f.name}',
      if (receivable) ...['dynamic extra', 'int? clientId'],
    ];
    final copyArgs = [
      for (final f in fields) '${f.name}: ${f.name} ?? this.${f.name}',
      if (receivable) ...[
        'extra: extra ?? this.extra',
        'clientId: clientId ?? this.clientId',
      ],
    ];
    out
      ..writeln()
      ..writeln('  /// Returns a copy with the given fields replaced.');
    if (overrideCopyWith) out.writeln('  @override');
    out.writeln(copyParams.isEmpty
        ? '  $name copyWith() => const $name();'
        : '  $name copyWith({\n${copyParams.map((p) => '    $p,\n').join()}'
            '  }) =>\n      $name(\n${copyArgs.map((a) => '        $a,\n').join()}'
            '      );');

    // TDLib name.
    out
      ..writeln()
      ..writeln('  /// TDLib type name.')
      ..writeln("  static const String CONSTRUCTOR = '${c.name}';")
      ..writeln()
      ..writeln('  @override')
      ..writeln('  String getConstructor() => CONSTRUCTOR;');
    if (c.canBeCalledSynchronously) {
      out
        ..writeln()
        ..writeln('  @override')
        ..writeln('  bool get canBeCalledSynchronously => true;');
    }
    return out.toString();
  }
}

String _library({
  required List<String> parts,
  required List<String> factories,
}) {
  return '''$_header
import 'dart:convert' show json;

${parts.map((p) => "part '$p';").join('\n')}

/// Base class of every TDLib object.
abstract class TdObject {
  const TdObject();

  /// "@extra" of the request this object answers; null for updates.
  dynamic get extra => null;

  /// Identifier of the TDLib client that sent this object, when known.
  int? get clientId => null;

  /// TDLib type name, e.g. `updateNewMessage`.
  String getConstructor();

  /// Converts this object to TDLib JSON.
  Map<String, dynamic> toJson();
}

/// Base class of every TDLib request. [R] is the type TDLib returns.
abstract class TdFunction<R extends TdObject> {
  const TdFunction();

  /// TDLib function name, e.g. `getMe`.
  String getConstructor();

  /// Converts this request to TDLib JSON, tagged with [extra] if given.
  Map<String, dynamic> toJson([dynamic extra]);

  /// Whether TDLib documents this request as callable through `td_execute`.
  bool get canBeCalledSynchronously => false;
}

/// A TDLib object of a type this API doesn't know.
final class UndecodedTdObject extends TdObject {
  const UndecodedTdObject(this.json);

  /// The raw TDLib JSON object.
  final Map<String, dynamic> json;

  @override
  dynamic get extra => json['@extra'];

  @override
  int? get clientId => _readClientId(json['@client_id']);

  @override
  String getConstructor() => _readString(json['@type']);

  @override
  Map<String, dynamic> toJson() => json;
}

/// Builds a TDLib object from its decoded JSON map.
typedef TdObjectFactory = TdObject Function(Map<String, dynamic> json);

/// Every concrete TDLib object type, keyed by its "@type".
final Map<String, TdObjectFactory> tdObjectFactories = {
${factories.join('\n')}
};

/// Converts a decoded TDLib JSON map. Unknown types become
/// [UndecodedTdObject].
TdObject convertMapToObject(Map<String, dynamic> json) {
  final factory = tdObjectFactories[json['@type']];
  return factory != null ? factory(json) : UndecodedTdObject(json);
}

/// Decodes a TDLib JSON string; null gives null.
TdObject? convertToObject(String? query) {
  if (query == null) return null;
  final decoded = json.decode(query);
  return decoded is Map<String, dynamic> ? convertMapToObject(decoded) : null;
}

// JSON readers shared by the generated classes. They accept missing or
// differently typed values (int64 sent as a string, 1 for 1.0).
int _readInt(Object? v) => switch (v) {
      int() => v,
      num() => v.toInt(),
      String() => int.tryParse(v) ?? 0,
      _ => 0,
    };

double _readDouble(Object? v) => v is num ? v.toDouble() : 0.0;

bool _readBool(Object? v) => v is bool && v;

String _readString(Object? v) => v is String ? v : '';

int? _readClientId(Object? v) => v is int ? v : null;

Map<String, dynamic> _readMap(Object? v) =>
    v is Map<String, dynamic> ? v : Map<String, dynamic>.from(v as Map);

T _readObject<T>(Object? v, T Function(Map<String, dynamic>) parse) =>
    parse(_readMap(v));

T? _readOptional<T>(Object? v, T Function(Map<String, dynamic>) parse) =>
    v == null ? null : parse(_readMap(v));

List<T> _readList<T>(Object? v, T Function(Object?) read) =>
    v is List ? [for (final e in v) read(e)] : <T>[];
''';
}
